package dev.mooner.neonjs.parser;

public class AssignmentPattern extends Node {
    public Node left;
    public final Node right;

    public AssignmentPattern(Node left, Node right) {
        this.left = left;
        this.right = right;
    }

    public Node getLeft() {
        return left;
    }

    public void setLeft(Node left) {
        this.left = left;
    }

    public Node getRight() {
        return right;
    }
}
