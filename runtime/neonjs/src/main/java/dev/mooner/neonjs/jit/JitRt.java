    public static Object callEval(Object fnv, Object thisV, Object[] args, Frame frame, int flags, int pc) {
        frame.pc = pc;
        if (fnv == frame.realm.evalFunction) return Rt.directEval(frame, args, (flags & 1) != 0);
        if ((flags & 2) != 0) return Interpreter.tailCall(frame, fnv, thisV, args);
        if (fnv instanceof JSObject object && object.isCallable()) return object.call(thisV, args);
        throw Rt.notCallable(fnv, frame.code, pc);
    }

