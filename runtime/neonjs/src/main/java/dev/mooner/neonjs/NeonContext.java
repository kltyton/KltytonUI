    /** Installs the loader used for {@code import} declarations and {@code import()}. */
    public void setModuleLoader(NeonModuleLoader loader) {
        this.userLoader = loader;
        installLoader();
    }

    /**
     * Defines an ES module that scripts can import by {@code specifier}, with the given named
     * exports (converted to JS; use the key {@code "default"} for a default export). Host modules
     * take precedence over the built-in modules of extensions and over the loader.
     */
    public void defineModule(String specifier, Map<String, ?> exports) {
        guarded(() -> {
            Map<String, Object> converted = new HashMap<>();
            for (Map.Entry<String, ?> entry : exports.entrySet()) {
                converted.put(entry.getKey(), bridge.toJS(entry.getValue()));
            }
            Modules.defineHostModule(realm, specifier, converted);
            installLoader();
            return null;
        });
    }

    private void installLoader() {
        Modules.setLoader(realm, new dev.mooner.neonjs.vm.ModuleLoader() {
            @Override
            public String resolve(String specifier, String referrerKey) {
                if (Modules.hostModule(realm, specifier) != null) {
                    return specifier;
                }
                Modules.Builtin builtin = Modules.builtin(realm, specifier);
                if (builtin != null) {
                    return builtin.name;
                }
                NeonModuleLoader loader = userLoader;
                if (loader == null) {
                    throw JSException.typeError("Cannot find module '" + specifier + "'");
                }
                return loaderCall(specifier, () -> loader.resolve(specifier, referrerKey));
            }

            @Override
            public ModuleSource load(String key, ModuleRequest request) {
                Map<String, Object> hostExports = Modules.hostModule(realm, key);
                if (hostExports != null) {
                    ModuleSource source = new ModuleSource(key, "");
                    source.setHostExports(hostExports);
                    source.setHostRealm(realm);
                    return source;
                }
                Modules.Builtin builtin = Modules.builtin(realm, key);
                if (builtin != null) {
                    return Modules.builtinSource(realm, builtin);
                }
                NeonModuleLoader loader = userLoader;
                if ("bytes".equals(request.getType())) {
                    byte[] bytes = loaderCall(request.getSpecifier(),
                            () -> loader == null ? null : loader.loadBytes(key));
                    if (bytes == null) {
                        throw JSException.typeError("Cannot find module '" + request.getSpecifier() + "'");
                    }
                    ModuleSource source = new ModuleSource(key, "");
                    source.setBytes(bytes);
                    return source;
                }
                String text = loaderCall(request.getSpecifier(),
                        () -> loader == null ? null : loader.load(key));
                if (text == null) {
                    throw JSException.typeError("Cannot find module '" + request.getSpecifier() + "'");
                }
                return new ModuleSource(key, text);
            }

            @Override
            public Map<String, Object> importMetaProperties(String key) {
                return Map.of("url", key);
            }
        });
    }

    /** Host loader failures become JS TypeErrors (so {@code import()} rejects instead of a host exception escaping). */
    private static <T> T loaderCall(String specifier, Supplier<T> block) {
        try {
            return block.get();
        } catch (JSException error) {
            throw error;
        } catch (TerminationException error) {
            throw error;
        } catch (Exception error) {
            // RuntimeException and host loaders that tunnel checked I/O failures
            throw JSException.typeError("Cannot load module '" + specifier + "': " + error.getMessage());
        }
    }

    /**
     * Evaluates {@code code} as an ES module named {@code name}. Returns the module namespace object
     * once evaluation (including top-level await) has completed.
     */
    public NeonValue evalModule(String code, String name, long timeoutMillis) {
        return guarded(() -> {
            ModuleSource source = new ModuleSource(name, code);
            HashMap<String, ModuleRecord> map = Modules.moduleMap(realm);
            ModuleRecord record = map.get(name);
            if (record == null) {
                record = Modules.parseModule(realm, source);
                map.put(name, record);
            }
            Modules.loadGraph(realm, record);
            Modules.link(record);
            JSPromise promise = Modules.evaluate(record);
            pumpUntil(timeoutMillis, () -> promise.state != JSPromise.PENDING);
            if (promise.state == JSPromise.REJECTED) {
                throw new JSException(promise.result);
            }
            if (promise.state == JSPromise.PENDING) {
                throw new NeonException("module evaluation did not complete (pending top-level await)");
            }
            return new NeonValue(this, Modules.namespaceOf(record, false));
        });
    }

    public NeonValue evalModule(String code, String name) {
        return evalModule(code, name, Long.MAX_VALUE);
    }

    /** Defines (or replaces) a global binding with a host value (converted to JS). */
    public void set(String name, Object value) {
        guarded(() -> {
            PropertyDescriptor descriptor = new PropertyDescriptor();
            descriptor.value = bridge.toJS(value);
            descriptor.writable = (Attr.ALL & Attr.WRITABLE) != 0;
            descriptor.enumerable = (Attr.ALL & Attr.ENUMERABLE) != 0;
            descriptor.configurable = (Attr.ALL & Attr.CONFIGURABLE) != 0;
            descriptor.present = PropertyDescriptor.HAS_VALUE | PropertyDescriptor.HAS_WRITABLE
                    | PropertyDescriptor.HAS_ENUMERABLE | PropertyDescriptor.HAS_CONFIGURABLE;
            realm.getGlobalObject().defineOwnProperty(name, descriptor);
            return null;
        });
    }

    public NeonValue get(String name) {
        return guarded(() -> {
            JSObject global = realm.getGlobalObject();
            return new NeonValue(this, global.get(name, global));
        });
    }

    /** Defines a global function implemented by the host. */
    public void setFunction(String name, HostFunction function) {
        set(name, createFunction(name, function));
    }

    /** Creates a JS function object backed by a host function (not bound to a global name). */
    public NeonValue createFunction(String name, HostFunction function) {
        return guarded(() -> {
            NativeFunction nativeFunction = nativeFunction(realm, name, 0, (f, thisArg, args, newTarget) -> {
                NeonValue[] wrapped = new NeonValue[args.length];
                for (int i = 0; i < args.length; i++) {
                    wrapped[i] = new NeonValue(this, args[i]);
                }
                try {
                    return bridge.toJS(function.call(wrapped));
                } catch (NeonException error) {
                    NeonValue guest = error.getGuestValue();
                    if (guest != null && guest.getContext() == this) {
                        throw new JSException(guest.getRaw());
                    }
                    throw new HostException(error);
                } catch (JSException error) {
                    throw error;
                } catch (TerminationException error) {
                    throw error;
                } catch (RuntimeException error) {
                    throw new HostException(error);
                }
            });
            return new NeonValue(this, nativeFunction);
        });
    }

    /** Exposes a host class as a global constructor / static namespace (subject to {@link HostAccess}). */
    public void exposeClass(String name, Class<?> cls) {
        guarded(() -> {
            if (!engine.hostAccess.isClassAccessible(cls)) {
                throw new NeonException("Host access policy does not allow class " + cls.getName());
            }
            realm.getGlobalObject().defineOwn(name, bridge.classObject(cls), Attr.WC);
            return null;
        });
    }

    /** Converts a host value into a JS value of this context. */
    public NeonValue asValue(Object host) {
        return guarded(() -> new NeonValue(this, bridge.toJS(host)));
    }

    /** Runs pending Promise jobs (microtasks). */
    public void runJobs() {
        guarded(() -> {
            agent.runJobs();
            return null;
        });
    }

    /**
     * Sets what receives the errors JS leaves uncaught while jobs run, so an event loop can report
     * them and go on. Without one (the default) such an exception ends the call running the jobs.
     */
    public void setUncaughtErrorHandler(UncaughtErrorHandler handler) {
        guarded(() -> {
            agent.uncaught = handler == null ? null : new Agent.UncaughtSink() {
                @Override
                public void exception(RuntimeException error) {
                    Throwable cause = error instanceof HostException
                            ? ((HostException) error).getHostCause() : error;
                    handler.uncaught(error instanceof JSException
                            ? toHostException((JSException) error)
                            : new NeonException("Host exception: " + cause, cause), false);
                }

                @Override
                public void rejection(JSPromise promise) {
                    handler.uncaught(toHostException(new JSException(promise.result)), true);
                }
            };
            return null;
        });
    }

    /**
     * Runs pending jobs and waits for external events until nothing is pending. Returns false if
     * work was still pending after {@code timeoutMillis}.
     */
    public boolean runEventLoop(long timeoutMillis) {
        return guarded(() -> pumpUntil(timeoutMillis, null));
    }

    public boolean runEventLoop() {
        return runEventLoop(Long.MAX_VALUE);
    }

    /**
     * Runs jobs, waiting for external events while any are pending, until {@code done} holds (true),
     * nothing more is pending (true without {@code done}, else false) or {@code timeoutMillis}
     * elapses (false). Call inside {@link #enter}.
     */
    public boolean pumpUntil(long timeoutMillis, BooleanSupplier done) {
        long start = System.nanoTime();
        while (true) {
            agent.runJobs();
            if (done != null && done.getAsBoolean()) {
                return true;
            }
            if (!agent.hasPendingExternal()) {
                return done == null;
            }
            long elapsed = (System.nanoTime() - start) / 1_000_000L;
            if (elapsed >= timeoutMillis) {
                return false;
            }
            // a wait inside JS (a host function awaiting a promise) keeps the context: its frames are live
            if (depth == 1 && lock.getHoldCount() == 1 && agent.topFrame == null) {
                awaitReleased(timeoutMillis - elapsed);
            } else {
                agent.awaitExternal(timeoutMillis - elapsed);
            }
        }
    }

    /**
     * {@code Agent.awaitExternal} without holding the context, so other threads can evaluate code
     * and call into it meanwhile (and run the tasks that arrive, as their calls run jobs). Their
     * evaluations start their own limits; this thread's are restored afterwards, and an interrupt
     * requested meanwhile ends the wait even if their start cleared it. Called at the top of
     * {@link #enter} only.
     */
    private void awaitReleased(long timeoutMillis) {
        if (agent.interruptRequested) {
            throw new InterruptedExecutionException("Execution interrupted");
        }
        long[] limits = agent.saveLimits();
        // other threads' enter / exit restore the current realm in their own order: an exit may clear it under this one
        Realm currentRealm = agent.currentRealm;
        long interrupts = agent.getInterruptCount();
        long deadline = agent.config.limitsPerTask ? 0L : agent.deadlineNanos;
        long end = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(timeoutMillis);
        depth = 0;
        lock.unlock();
        try {
            // another thread may run the last tasks meanwhile: then nothing will be posted
            while (!closed && agent.getInterruptCount() == interrupts && agent.hasPendingExternal()) {
                // differences, not comparisons: end overflows for an unbounded timeout
                long now = System.nanoTime();
                long wait = end - now;
                if (deadline != 0L) {
                    wait = Math.min(wait, deadline - now);
                }
                if (wait <= 0) {
                    break;
                }
                if (agent.waitForExternal(Math.min(wait, Agent.WAIT_SLICE_NANOS))) {
                    break;
                }
            }
        } finally {
            // not acquire(): its time limit is for threads that may wait on each other, and this one holds nothing
            lock.lock();
            depth = 1;
            agent.currentRealm = currentRealm;
            agent.restoreLimits(limits);
        }
        if (agent.getInterruptCount() != interrupts) {
            throw new InterruptedExecutionException("Execution interrupted");
        }
        if (deadline != 0L) {
            agent.checkWaitLimits();
        }
    }

    /** Requests termination of the currently running evaluation and of an event loop waiting in the context. */
    public void interrupt() {
        agent.requestInterrupt();
    }

    @Override
    public void close() {
        closed = true;
        // withdraw pending Atomics.waitAsync waiters (unlink them, cancel their timers) so nothing outlives the context
        agent.closeExternal();
        // and code still waiting for the background compiler
        JitQueue.cancel(agent);
    }

