    private void installJavaGlobal(Realm targetRealm, HostBridge targetBridge, Agent targetAgent) {
        JSObject javaObject = new JSObject(targetRealm.getObjectPrototype());
        javaObject.defineOwn("type", nativeFunction(targetRealm, "type", 1, (f, thisArg, args, newTarget) -> {
            String name = Ops.toString(arg(args, 0));
            ClassLoader loader = Thread.currentThread().getContextClassLoader();
            if (loader == null) {
                loader = getClass().getClassLoader();
            }
            TypeEntry cached = typeCache.get(name);
            if (cached != null && cached.loader == loader) {
                return cached.object;
            }
            HostClassObject object = targetBridge.classObject(lookupClass(name, loader));
            typeCache.put(name, new TypeEntry(loader, object));
            return object;
        }), Attr.WC);
        javaObject.defineOwn("from", nativeFunction(targetRealm, "from", 1, (f, thisArg, args, newTarget) -> {
            Object value = arg(args, 0);
            if (!(value instanceof HostObject)) {
                throw JSException.typeError("Java.from requires a Java array or collection");
            }
            Object target = ((HostObject) value).target;
            ArrayList<Object> out = new ArrayList<>();
            if (target instanceof Iterable<?>) {
                for (Object element : (Iterable<?>) target) {
                    addJavaElement(out, targetBridge, element, f);
                }
            } else if (target.getClass().isArray()) {
                int length = Array.getLength(target);
                for (int i = 0; i < length; i++) {
                    addJavaElement(out, targetBridge, Array.get(target, i), f);
                }
            } else {
                throw JSException.typeError("Java.from requires a Java array or collection");
            }
            return JSArray.of(f.realm, out);
        }), Attr.WC);
        javaObject.defineOwn("to", nativeFunction(targetRealm, "to", 2, (f, thisArg, args, newTarget) -> {
            // Java.to(jsArray, "int[]" | Java.type(...)) -> Java array or List
            Object target = arg(args, 1);
            Class<?> type;
            if (target instanceof HostClassObject) {
                type = ((HostClassObject) target).cls;
            } else if (target == Undefined.INSTANCE) {
                type = Object[].class;
            } else {
                type = lookupClass(Ops.toString(target));
            }
            return targetBridge.toJS(targetBridge.convertTo(arg(args, 0), type));
        }), Attr.WC);
        javaObject.defineOwn("extend", nativeFunction(targetRealm, "extend", 1, (f, thisArg, args, newTarget) -> {
            // Java.extend(Type..., [impl]): a subclass / implementation whose methods are JS functions
            if (!engine.hostAccess.allowImplementations) {
                throw JSException.typeError("Host access policy does not allow Java.extend");
            }
            Object last = args.length == 0 ? null : args[args.length - 1];
            JSObject classImpl = last instanceof JSObject && !(last instanceof HostClassObject)
                    ? (JSObject) last : null;
            Object[] typeArgs = classImpl != null
                    ? Arrays.copyOfRange(args, 0, args.length - 1) : args;
            if (typeArgs.length == 0) {
                throw JSException.typeError("Java.extend requires at least one Java type");
            }
            ArrayList<Class<?>> types = new ArrayList<>(typeArgs.length);
            StringBuilder display = new StringBuilder();
            for (Object item : typeArgs) {
                if (!(item instanceof HostClassObject)) {
                    throw JSException.typeError(
                            "Java.extend: " + Ops.describe(item) + " is not a Java type");
                }
                Class<?> cls = ((HostClassObject) item).cls;
                if (!engine.hostAccess.isClassAccessible(cls) || cls.isArray() || cls.isPrimitive()) {
                    throw JSException.typeError("Java.extend: " + cls.getName() + " cannot be extended");
                }
                types.add(cls);
                if (display.length() > 0) {
                    display.append('+');
                }
                display.append(cls.getSimpleName());
            }
            AdapterClass adapter = adapterCache.get(types);
            if (adapter == null) {
                CodeDefiner definer = targetAgent.config.codeDefiner != null
                        ? targetAgent.config.codeDefiner : CodeDefiners.getDefault();
                adapter = Adapters.INSTANCE.generate(types, definer);
                adapterCache.put(types, adapter);
            }
            return new AdapterClassObject(targetBridge, adapter, classImpl, display.toString());
        }), Attr.WC);
        javaObject.defineOwn("super", nativeFunction(targetRealm, "super", 1, (f, thisArg, args, newTarget) -> {
            Object value = arg(args, 0);
            if (!(value instanceof HostObject)) {
                throw JSException.typeError("Java.super requires a Java adapter instance");
            }
            HostObject object = (HostObject) value;
            AdapterClass entry = null;
            for (AdapterClass candidate : adapterCache.values()) {
                if (candidate.cls.isInstance(object.target)) {
                    entry = candidate;
                    break;
                }
            }
            if (entry == null) {
                throw JSException.typeError("Java.super requires an instance of a Java.extend adapter");
            }
            return new AdapterClassObject(targetBridge, entry, null, entry.cls.getSimpleName()).superOf(object);
        }), Attr.WC);
        javaObject.defineOwn("isJavaObject",
                nativeFunction(targetRealm, "isJavaObject", 1,
                        (f, thisArg, args, newTarget) -> arg(args, 0) instanceof HostObject), Attr.WC);
        javaObject.defineOwn("isType",
                nativeFunction(targetRealm, "isType", 1,
                        (f, thisArg, args, newTarget) -> arg(args, 0) instanceof HostClassObject), Attr.WC);
        targetRealm.getGlobalObject().defineOwn("Java", javaObject, Attr.WC);
    }

    private void addJavaElement(List<Object> out, HostBridge targetBridge, Object value, NativeFunction function) {
        if (out.size() >= HostBridge.MAX_ARRAY_LENGTH) {
            throw JSException.rangeError("Java.from: collection too large");
        }
        out.add(targetBridge.toJS(value));
        if ((out.size() & 1023) == 0) {
            function.realm.agent.checkInterrupt();
        }
    }

    /** Resolves a class name for the Java global, applying the lookup filter and the class access policy. */
    private Class<?> lookupClass(String name, ClassLoader loader) {
        if (!engine.hostAccess.isLookupAllowed(name)) {
            throw JSException.typeError("Access to host class " + name + " is not allowed");
        }
        Class<?> cls;
        try {
            cls = HostBridge.classForName(name, loader);
        } catch (ClassNotFoundException error) {
            throw JSException.typeError("Unknown host class " + name);
        } catch (LinkageError error) {
            throw JSException.typeError("Cannot load host class " + name);
        }
        if (!engine.hostAccess.isClassAccessible(cls)) {
            throw JSException.typeError("Access to host class " + name + " is not allowed");
        }
        return cls;
    }

    private Class<?> lookupClass(String name) {
        ClassLoader loader = Thread.currentThread().getContextClassLoader();
        if (loader == null) {
            loader = getClass().getClassLoader();
        }
        return lookupClass(name, loader);
    }

    private static NativeFunction nativeFunction(Realm realm, String name, int length, NativeImpl impl) {
        return new NativeFunction(realm, name, length, impl, false, realm.getFunctionPrototype(), null);
    }

    private static Object arg(Object[] args, int index) {
        return index < args.length ? args[index] : Undefined.INSTANCE;
    }

    private static final class TypeEntry {
        final ClassLoader loader;
        final HostClassObject object;

        TypeEntry(ClassLoader loader, HostClassObject object) {
            this.loader = loader;
            this.object = object;
        }
    }
