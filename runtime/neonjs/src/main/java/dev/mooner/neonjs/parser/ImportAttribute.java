package dev.mooner.neonjs.parser;

public class ImportAttribute extends Node {
    public final String key;
    public final String value;

    public ImportAttribute(String key, String value) {
        this.key = key;
        this.value = value;
    }

    public String getKey() {
        return key;
    }

    public String getValue() {
        return value;
    }
}
