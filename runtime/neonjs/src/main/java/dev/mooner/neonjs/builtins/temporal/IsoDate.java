package dev.mooner.neonjs.builtins.temporal;

/** ISO Date Record. The year may lie outside the Temporal range but always fits an Int. */
public final class IsoDate {
    public final int year;
    public final int month;
    public final int day;

    public IsoDate(int year, int month, int day) {
        this.year = year;
        this.month = month;
        this.day = day;
    }

    public int getYear() {
        return year;
    }

    public int getMonth() {
        return month;
    }

    public int getDay() {
        return day;
    }
}
